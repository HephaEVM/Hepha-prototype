// runUnboundStack handles an eligible Hepha frame without constructing a plan.
func (evm *EVM) runUnboundStack(contract *Contract, input []byte, readOnly bool) (ret []byte, err error, latency time.Duration) {
	// Increment the call depth which is restricted to 1024
	evm.depth++
	defer func() { evm.depth-- }()

	// Make sure the readOnly is only set if we aren't in readOnly yet.
	// This also makes sure that the readOnly flag isn't removed for child calls.
	if readOnly && !evm.readOnly {
		evm.readOnly = true
		defer func() { evm.readOnly = false }()
	}

	// Reset the previous call's return data. It's unimportant to preserve the old buffer
	// as every returning call will return new data anyway.
	evm.returnData = nil

	// Don't bother with the execution if there's no code.
	if len(contract.Code) == 0 {
		return nil, nil, 0
	}

	var (
		op          OpCode     // current opcode
		jumpTable   *JumpTable = evm.table
		mem                    = NewMemory() // bound memory
		stack                  = newstack()  // local stack
		callContext            = &ScopeContext{
			Memory:   mem,
			Stack:    stack,
			Contract: contract,
		}
		// For optimisation reason we're using uint64 as the program counter.
		// It's theoretically possible to go above 2^64. The YP defines the PC
		// to be uint256. Practically much less so feasible.
		pc   = uint64(0) // program counter
		cost uint64
		// copies used by tracer
		pcCopy    uint64 // needed for the deferred EVMLogger
		gasCopy   uint64 // for EVMLogger to log gas remaining before execution
		logged    bool   // deferred EVMLogger should ignore already logged steps
		res       []byte // result of the opcode execution function
		debug     = evm.Config.Tracer != nil
		isEIP4762 = evm.chainRules.IsEIP4762
	)
	// Don't move this deferred function, it's placed before the OnOpcode-deferred method,
	// so that it gets executed _after_: the OnOpcode needs the stacks before
	// they are returned to the pools
	defer func() {
		returnStack(stack)
		mem.Free()
	}()
	contract.Input = input

	if debug {
		defer func() { // this deferred method handles exit-with-error
			if err == nil {
				return
			}
			if !logged && evm.Config.Tracer.OnOpcode != nil {
				evm.Config.Tracer.OnOpcode(pcCopy, byte(op), gasCopy, cost, callContext, evm.returnData, evm.depth, VMErrorFromErr(err))
			}
			if logged && evm.Config.Tracer.OnFault != nil {
				evm.Config.Tracer.OnFault(pcCopy, byte(op), gasCopy, cost, callContext, evm.depth, VMErrorFromErr(err))
			}
		}()
	}
	// The Interpreter main run loop (contextual). This loop runs until either an
	// explicit STOP, RETURN or SELFDESTRUCT is executed, an error occurred during
	// the execution of one of the operations or until the done flag is set by the
	// parent context.
	_ = jumpTable[0] // nil-check the jumpTable out of the loop
	// BEGIN IDENTICAL LOOP TIMING ADAPTER
	now := time.Now()
	if timing := evm.Config.LoopTiming; timing != nil && evm.depth == 1 {
		// Registered after frame-cleanup defers: early returns are measured before
		// cleanup, matching the normal lat boundary below. Normal paths reuse lat.
		defer func() {
			elapsed := latency
			if elapsed == 0 {
				elapsed = time.Since(now)
				timing.EarlyExits++
			}
			timing.Nanoseconds += elapsed.Nanoseconds()
			timing.Runs++
			if contract.IsDeployment {
				timing.CreationRuns++
			} else {
				// Reproduce the pre-existing top-level Call accumulator as well.
				timing.LegacyCallMicros += latency.Microseconds()
			}
		}()
	}
	// END IDENTICAL LOOP TIMING ADAPTER
	useSpan := evm.Config.StreamRegions != nil && jumpTable == stackSpanRules && evm.Config.Tracer == nil && len(evm.Config.ExtraEips) == 0
	for {
		if debug {
			// Capture pre-execution values for tracing.
			logged, pcCopy, gasCopy = false, pc, contract.Gas
		}

		if isEIP4762 && !contract.IsDeployment && !contract.IsSystemCall {
			// if the PC ends up in a new "chunk" of verkleized code, charge the
			// associated costs.
			contractAddr := contract.Address()
			consumed, wanted := evm.TxContext.AccessEvents.CodeChunksRangeGas(contractAddr, pc, 1, uint64(len(contract.Code)), false, contract.Gas)
			contract.UseGas(consumed, evm.Config.Tracer, tracing.GasChangeWitnessCodeChunk)
			if consumed < wanted {
				return nil, ErrOutOfGas, 0
			}
		}

		// Get the operation from the jump table and validate the stack to ensure there are
		// enough stack items available to perform the operation.
		op = contract.GetOp(pc)
		// Common residue between bound regions. Only consume supported fixed-cost ops;
		// all exceptional cases enter the ordinary interpreter at their original PC.
		if useSpan {
			if stackSpanStart[op] {
				if end, ok := executeStackSpan(evm, contract, stack, contract.Code, pc); ok {
					pc = end
					continue
				}
			}
		} else if op >= PUSH1 && op <= SWAP16 && !debug && !isEIP4762 && len(evm.Config.ExtraEips) == 0 {
			entry := jumpTable[op]
			depth := len(stack.data)
			if depth >= entry.minStack && depth <= entry.maxStack && contract.Gas >= entry.constantGas {
				switch {
				case op <= PUSH32:
					width := uint64(op-PUSH1) + 1
					next := pc + width + 1
					if next > uint64(len(contract.Code)) {
						break
					}
					arg := contract.Code[pc+1 : next]
					// A short literal followed by an unpatched branch can remain in a register.
					if width <= 2 && next < uint64(len(contract.Code)) {
						branch := OpCode(contract.Code[next])
						if (branch == JUMP || branch == JUMPI && depth > 0) && !evm.abort.Load() {
							left := contract.Gas - entry.constantGas
							branchCost := jumpTable[branch].constantGas
							if left >= branchCost {
								taken := branch == JUMP || !stack.data[depth-1].IsZero()
								dest := uint64(arg[0])
								if width == 2 {
									dest = dest<<8 | uint64(arg[1])
								}
								if !taken || dest < uint64(len(contract.Code)) && OpCode(contract.Code[dest]) == JUMPDEST && contract.isCode(dest) {
									if branch == JUMPI {
										stack.data = stack.data[:depth-1]
									}
									contract.Gas = left - branchCost
									pc = next + 1
									if taken {
										pc = dest
									}
									if paperCountInstructions {
										paperInterpreted += 2
									}
									continue
								}
							}
						}
					}
					var literal uint256.Int
					switch width {
					case 1:
						literal.SetUint64(uint64(arg[0]))
					case 2:
						literal.SetBytes2(arg)
					default:
						literal.SetBytes(arg)
					}
					stack.push(&literal)
					contract.Gas -= entry.constantGas
					pc = next
					if paperCountInstructions {
						paperInterpreted++
					}
					continue
				case op <= DUP16:
					stack.dup(int(op-DUP1) + 1)
				default:
					i := depth - 2 - int(op-SWAP1)
					stack.data[depth-1], stack.data[i] = stack.data[i], stack.data[depth-1]
				}
				if op >= DUP1 {
					contract.Gas -= entry.constantGas
					pc++
					if paperCountInstructions {
						paperInterpreted++
					}
					continue
				}
			}
		}

		if paperCountInstructions {
			paperInterpreted++
		}
		operation := jumpTable[op]
		cost = operation.constantGas // For tracing
		// Validate stack
		if sLen := stack.len(); sLen < operation.minStack {
			return nil, &ErrStackUnderflow{stackLen: sLen, required: operation.minStack}, 0
		} else if sLen > operation.maxStack {
			return nil, &ErrStackOverflow{stackLen: sLen, limit: operation.maxStack}, 0
		}
		// for tracing: this gas consumption event is emitted below in the debug section.
		if contract.Gas < cost {
			return nil, ErrOutOfGas, 0
		} else {
			contract.Gas -= cost
		}

		// All ops with a dynamic memory usage also has a dynamic gas cost.
		var memorySize uint64
		if operation.dynamicGas != nil {
			// calculate the new memory size and expand the memory to fit
			// the operation
			// Memory check needs to be done prior to evaluating the dynamic gas portion,
			// to detect calculation overflows
			if operation.memorySize != nil {
				memSize, overflow := operation.memorySize(stack)
				if overflow {
					return nil, ErrGasUintOverflow, 0
				}
				// memory is expanded in words of 32 bytes. Gas
				// is also calculated in words.
				if memorySize, overflow = math.SafeMul(toWordSize(memSize), 32); overflow {
					return nil, ErrGasUintOverflow, 0
				}
			}
			// Consume the gas and return an error if not enough gas is available.
			// cost is explicitly set so that the capture state defer method can get the proper cost
			var dynamicCost uint64
			dynamicCost, err = operation.dynamicGas(evm, contract, stack, mem, memorySize)
			cost += dynamicCost // for tracing
			if err != nil {
				return nil, fmt.Errorf("%w: %v", ErrOutOfGas, err), 0
			}
			// for tracing: this gas consumption event is emitted below in the debug section.
			if contract.Gas < dynamicCost {
				return nil, ErrOutOfGas, 0
			} else {
				contract.Gas -= dynamicCost
			}
		}

		// Do tracing before potential memory expansion
		if debug {
			if evm.Config.Tracer.OnGasChange != nil {
				evm.Config.Tracer.OnGasChange(gasCopy, gasCopy-cost, tracing.GasChangeCallOpCode)
			}
			if evm.Config.Tracer.OnOpcode != nil {
				evm.Config.Tracer.OnOpcode(pc, byte(op), gasCopy, cost, callContext, evm.returnData, evm.depth, VMErrorFromErr(err))
				logged = true
			}
		}
		if memorySize > 0 {
			mem.Resize(memorySize)
		}

		// execute the operation
		res, err = operation.execute(&pc, evm, callContext)
		if err != nil {
			break
		}
		pc++
	}

	lat := time.Since(now)
	if err == errStopToken {
		err = nil // clear stop token error
	}

	return res, err, lat
}
